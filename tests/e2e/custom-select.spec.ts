import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

test('custom selects support paged search, keyboard, disabled options and modal focus', async ({page}) => {
  test.skip(!process.env.CLIPPER_E2E_EMAIL, 'Disposable QA account required')
  page.setDefaultTimeout(15000)
  const errors:string[]=[]; page.on('pageerror', e=>errors.push(e.message))
  await page.setViewportSize({width:1366,height:768})
  await page.goto('/login')
  await page.getByLabel('Email',{exact:true}).fill(process.env.CLIPPER_E2E_EMAIL!)
  await page.getByLabel('Kata sandi',{exact:true}).fill(process.env.CLIPPER_E2E_PASSWORD!)
  await page.getByLabel('Kata sandi',{exact:true}).press('Enter')
  await expect(page.getByRole('heading',{name:'Proyek',exact:true})).toBeVisible()
  const filter=page.getByRole('combobox',{name:'Filter status',exact:true})
  await filter.click()
  await expect(page.getByRole('option')).toHaveCount(6)
  await page.getByRole('button',{name:'Pilihan berikutnya',exact:true}).click()
  await expect(page.getByRole('option',{name:'Tidak ditemukan ucapan',exact:true})).toBeVisible()
  await page.getByRole('searchbox',{name:'Cari Filter status',exact:true}).fill('memvalidasi')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.getByRole('searchbox',{name:'Cari Filter status',exact:true}).press('Escape')
  await expect(filter).toBeFocused()
  await filter.press('Enter'); await filter.press('End'); await filter.press('Home'); await filter.press('Enter')
  await expect(filter).toContainText('Semua status')
  // Browser-only provider fixtures; no account is connected and no post is sent.
  await page.route('**/api/v1/social/exports',route=>route.fulfill({json:{items:Array.from({length:20},(_,i)=>({id:`select-qa-${i}`,title:`Pilihan video ${i+1}`,revision:1,preview_url:''}))}}))
  await page.route('**/api/v1/social/accounts',route=>route.fulfill({json:{items:[{id:'select-qa-account',name:'Kreator QA',platform:'tiktok',connected:true}],platforms:['youtube','instagram','tiktok'].map(id=>({id,configured:true,publishing_ready:true,callback_url:''}))}}))
  await page.route('**/api/v1/social/accounts/select-qa-account/creator-info',route=>route.fulfill({json:{creator_nickname:'Kreator QA',privacy_level_options:['SELF_ONLY','PUBLIC_TO_EVERYONE'],max_video_post_duration_sec:60}}))
  await page.goto('/calendar')
  await expect(page.getByRole('heading',{name:'Kalender',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Tambah jadwal',exact:true}).click()
  const outputs=page.getByRole('combobox',{name:'Video hasil ekspor',exact:true})
  await outputs.click()
  await outputs.press('End')
  await expect(page.getByRole('option',{name:'Pilihan video 20 / revisi 1',exact:true})).toBeVisible()
  await outputs.press('Enter')
  await expect(outputs).toContainText('Pilihan video 20')
  await outputs.click()
  await page.getByRole('searchbox',{name:'Cari Video hasil ekspor',exact:true}).fill('tidak ada')
  await expect(page.getByText('Tidak ada pilihan yang cocok.',{exact:true})).toBeVisible()
  await page.getByRole('searchbox',{name:'Cari Video hasil ekspor',exact:true}).fill('video 17')
  await page.getByRole('option',{name:'Pilihan video 17 / revisi 1',exact:true}).click()
  await outputs.click()
  await expect(page.getByRole('option',{name:'Pilihan video 17 / revisi 1',exact:true})).toHaveAttribute('aria-selected','true')
  await outputs.press('Escape')
  async function choose(label:string,option:string) { await page.getByRole('combobox',{name:label,exact:true}).click(); await page.getByRole('option',{name:option,exact:true}).click() }
  await choose('Platform publikasi','TikTok')
  await choose('Akun tujuan','Kreator QA')
  await page.getByRole('button',{name:'Opsi publikasi',exact:true}).click()
  await choose('Visibilitas publikasi','Semua orang')
  await page.getByLabel('Konten mempromosikan merek, produk, atau layanan',{exact:true}).check()
  await page.getByLabel('Kemitraan merek pihak ketiga (Paid partnership)',{exact:true}).check()
  const privacy=page.getByRole('combobox',{name:'Visibilitas publikasi',exact:true})
  await privacy.click()
  await expect(page.getByRole('option',{name:'Hanya saya',exact:true})).toHaveAttribute('aria-disabled','true')
  await privacy.press('Home'); await privacy.press('Enter')
  await expect(privacy).toContainText('Semua orang')
  await privacy.click(); await privacy.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(privacy).toBeFocused()
  const dir=resolve(import.meta.dirname,'../../.artifacts/custom-select');mkdirSync(dir,{recursive:true})
  await privacy.click()
  await page.screenshot({path:resolve(dir,'desktop.png')})
  await expect(page.locator('select')).toHaveCount(0)
  const rect=await page.locator('.select-popover').boundingBox()
  expect(rect!.y).toBeGreaterThanOrEqual(0);expect(rect!.y+rect!.height).toBeLessThanOrEqual(768)
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:resolve(dir,'mobile.png')})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
  expect(errors).toEqual([])
})
