import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('thumbnail uses the selected frame, fits editable titles and downloads JPG in all formats', async ({ page }, testInfo) => {
  test.skip(!process.env.CLIPPER_E2E_EMAIL || !process.env.CLIPPER_E2E_PROJECT, 'Account and ready video project required')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(process.env.CLIPPER_E2E_EMAIL!)
  await page.getByLabel('Kata sandi', { exact: true }).fill(process.env.CLIPPER_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
  await page.goto(`/projects/${process.env.CLIPPER_E2E_PROJECT}`)
  await page.getByRole('button', { name: 'Buat thumbnail', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Buat thumbnail', exact: true })
  const canvas = dialog.locator('canvas')
  await expect(canvas).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Unduh JPG' })).toBeEnabled()
  const original = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
  await dialog.getByLabel('Waktu (detik)').fill('5')
  await dialog.getByLabel('Waktu (detik)').press('Tab')
  await expect(dialog).toContainText('00:05.000')
  await expect.poll(() => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(original)
  await dialog.getByLabel('Judul thumbnail').fill('CERITA DI BALIK LAYAR\nMOMEN PALING SERU!')
  const styles = new Set<string>()
  for (const preset of ['Gradasi', 'Neon', 'Pop 3D']) {
    await dialog.getByRole('button', { name: preset, exact: true }).click()
    await expect(dialog.getByRole('button', { name: preset, exact: true })).toHaveAttribute('aria-pressed', 'true')
    const before = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
    await dialog.getByRole('button', { name: 'Biru ungu', exact: true }).click()
    await expect.poll(() => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(before)
    styles.add(await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL()))
    await canvas.screenshot({ path: testInfo.outputPath(`style-${preset.replace(' ', '-')}.png`) })
    await dialog.getByRole('button', { name: 'Emas oranye', exact: true }).click()
  }
  expect(styles.size).toBe(3)
  await dialog.getByLabel('Judul thumbnail').fill('Cerita di balik layar\nMomen paling seru!')
  const capitalized = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
  await dialog.getByLabel('Huruf kapital', { exact: true }).uncheck()
  await expect.poll(() => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(capitalized)
  await dialog.getByRole('combobox', { name: 'Font thumbnail', exact: true }).click()
  await page.getByRole('option', { name: 'Modern', exact: true }).click()
  const modern = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
  await dialog.getByRole('combobox', { name: 'Font thumbnail', exact: true }).click()
  await page.getByRole('option', { name: 'Display tebal', exact: true }).click()
  await expect.poll(() => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(modern)
  await dialog.getByLabel('Huruf kapital', { exact: true }).check()
  await page.screenshot({ path: testInfo.outputPath('thumbnail-desktop.png') })
  for (const [label, width, height] of [['YouTube · 16:9', 1280, 720], ['Vertikal · 9:16', 720, 1280], ['Persegi · 1:1', 1080, 1080]] as const) {
    await dialog.getByRole('combobox', { name: 'Format thumbnail' }).click()
    await page.getByRole('option', { name: label, exact: true }).click()
    await expect(canvas).toHaveAttribute('width', String(width))
    await expect(canvas).toHaveAttribute('height', String(height))
    const downloadPromise = page.waitForEvent('download')
    await dialog.getByRole('button', { name: 'Unduh JPG' }).click()
    const download = await downloadPromise
    expect(download.suggestedFilename()).toMatch(/\.jpg$/)
    const path = testInfo.outputPath(download.suggestedFilename())
    await download.saveAs(path)
    const bytes = await readFile(path)
    expect([...bytes.subarray(0, 3)]).toEqual([255, 216, 255])
    expect(bytes.toString('base64')).toBe(await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL('image/jpeg', .9).split(',')[1]))
    // Decode the actual download, not just the preview canvas.
    const actualSize = await page.evaluate(async data => {
      const blob = await (await fetch(`data:image/jpeg;base64,${data}`)).blob()
      const bitmap = await createImageBitmap(blob)
      const size = [bitmap.width, bitmap.height]; bitmap.close(); return size
    }, bytes.toString('base64'))
    expect(actualSize).toEqual([width, height])
  }
  await dialog.getByRole('button', { name: 'Putih dengan latar gelap', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Posisi teks thumbnail' }).click()
  await page.getByRole('option', { name: 'Atas', exact: true }).click()
  await dialog.getByLabel('Tampilkan seluruh frame').check()
  await dialog.getByLabel('Judul thumbnail').fill('JudulPanjangTanpaSpasi'.repeat(8))
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog).toBeVisible()
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('thumbnail-mobile.png') })
  await dialog.getByRole('button', { name: 'Tutup', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Buat thumbnail', exact: true }).click()
  await expect(canvas).toBeVisible()
  await expect(canvas).toHaveAttribute('width', '1280')
  await dialog.getByRole('button', { name: 'Tutup', exact: true }).click()

  // Exercise the export entry point with a browser-only fixture backed by the
  // authenticated source asset; no render job or project mutation is needed.
  const assetUrl = await page.locator('.source-player video').getAttribute('src')
  const assetId = assetUrl!.split('/').at(-2)
  await page.route(`**/projects/${process.env.CLIPPER_E2E_PROJECT}/exports?*`, route => route.fulfill({ json: {
    items: [{ id: 'thumbnail-ui-fixture', clip_title: 'Judul ekspor thumbnail', revision: 1, status: 'succeeded', config: {},
      mp4_asset: { id: assetId, state: 'ready', bytes: 1000, metadata: {} }, created_at: '2026-01-01T00:00:00Z' }], total: 1,
  } }))
  await page.reload()
  await page.getByRole('tab', { name: 'Ekspor', exact: true }).click()
  await page.getByRole('button', { name: 'Thumbnail', exact: true }).click()
  await expect(dialog.getByLabel('Judul thumbnail')).toHaveValue('Judul ekspor thumbnail')
  await expect(canvas).toBeVisible()
  await dialog.getByRole('button', { name: 'Tutup', exact: true }).click()
  await page.route(`**${assetUrl}`, route => route.abort())
  await page.getByRole('button', { name: 'Thumbnail', exact: true }).click()
  await expect(dialog).toContainText('Video tidak dapat dimuat.')
  await expect(dialog.getByRole('button', { name: 'Unduh JPG' })).toBeDisabled()
  expect(errors).toEqual([])
})
