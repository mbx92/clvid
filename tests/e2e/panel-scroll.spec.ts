import { test, expect } from '@playwright/test'

test('export history scrolls inside its panel while preview and actions stay fixed', async ({page,context}) => {
  test.skip(!process.env.CLIPPER_E2E_WORKSPACE_CLIP_ID, 'Disposable QA account required')
  await page.setViewportSize({width:1366,height:768})
  await page.goto('/login')
  await page.getByLabel('Email',{exact:true}).fill(process.env.CLIPPER_E2E_EMAIL!)
  await page.getByLabel('Kata sandi',{exact:true}).fill(process.env.CLIPPER_E2E_PASSWORD!)
  await page.getByLabel('Kata sandi',{exact:true}).press('Enter')
  await expect(page.getByRole('heading',{name:'Proyek',exact:true})).toBeVisible()
  const id=process.env.CLIPPER_E2E_WORKSPACE_CLIP_ID!
  const clip=await (await context.request.get(`/api/v1/clips/${id}`)).json()
  const exports=Array.from({length:20},(_,i)=>({id:`paging-qa-${i}`,clip_title:`Ekspor QA ${i+1}`,revision:1,status:'ready',config:{resolution:720},created_at:'2026-11-01T00:00:00Z',mp4_asset:clip.source_asset}))
  await page.route(`**/api/v1/projects/${clip.project_id}/exports?*`,r=>r.fulfill({json:{items:exports,total:20,page:1,page_size:20}}))
  await page.goto(`/clips/${id}`)
  await page.getByRole('tab',{name:'Ekspor',exact:true}).click()
  await expect(page.locator('.export-row')).toHaveCount(20)
  const panel=page.getByRole('region',{name:'Daftar ekspor',exact:true})
  const header=await page.locator('.editor-header').boundingBox()
  const preview=await page.locator('.player-matte').boundingBox()
  await panel.hover(); await page.mouse.wheel(0,800)
  await expect.poll(()=>panel.evaluate(e=>e.scrollTop)).toBeGreaterThan(0)
  expect((await page.locator('.editor-header').boundingBox())!.y).toBe(header!.y)
  expect((await page.locator('.player-matte').boundingBox())!.y).toBe(preview!.y)
  await panel.focus(); await page.keyboard.press('End')
  await expect(page.getByRole('heading',{name:'Ekspor QA 20',exact:true})).toBeInViewport()
  await expect(page.getByRole('button',{name:'Ekspor',exact:true})).toBeInViewport()
  expect(await page.locator('.export-row h3').allTextContents()).toEqual(exports.map(e=>e.clip_title))
  await page.setViewportSize({width:1366,height:1080})
  await expect(page.locator('.export-row')).toHaveCount(20)
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+2 && window.scrollY===0)).toBe(true)
  await page.route('**/api/v1/social/posts?*',r=>r.fulfill({json:{items:Array.from({length:20},(_,i)=>({id:`agenda-qa-${i}`,title:`Agenda QA ${i+1}`,caption:'Konten uji scroll agenda.',platform:'youtube',status:'draft',scheduled_at:new Date().toISOString(),created_at:new Date(i*1000).toISOString(),options:{}}))}}))
  await page.goto('/calendar')
  const agenda=page.getByRole('region',{name:'Daftar agenda',exact:true})
  await expect(page.locator('.agenda-post')).toHaveCount(20)
  const calendar=await page.locator('.calendar-panel').boundingBox()
  await agenda.hover(); await page.mouse.wheel(0,800)
  await expect.poll(()=>agenda.evaluate(e=>e.scrollTop)).toBeGreaterThan(0)
  expect(await page.locator('.calendar-panel').boundingBox()).toEqual(calendar)
  await agenda.focus(); await page.keyboard.press('End')
  await expect(page.getByRole('heading',{name:'Agenda QA 20',exact:true})).toBeInViewport()
  expect(await page.evaluate(()=>window.scrollY)).toBe(0)
})
