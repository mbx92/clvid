def test_mfcc_preserves_pcm_amplitude_and_silence_is_finite():
    samples = np.arange(1600, dtype=np.int16) - 800
    features = mfcc_pcm16(samples)
    assert features.shape == (9, 13)
    np.testing.assert_allclose(mfcc_pcm16(samples * 2)[:, 0] - features[:, 0], np.log(4), atol=1e-12)
    assert np.isfinite(mfcc_pcm16(np.zeros(1600, dtype=np.int16))).all()
    with pytest.raises(ValueError):
        mfcc_pcm16(np.array([], dtype=np.int16))


